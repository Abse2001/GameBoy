export const GbaReferenceButtonContact = ({
  reference,
  name,
  ...props
}: PushButtonProps & {
  reference: keyof typeof gbaReferenceButtonPlacements
}) => {
  const geometry = contactGeometry[reference]
  const pads = [
    { pin: "pin1", alias: "signal", points: geometry.signal[0] },
    { pin: "pin2", alias: "ground", points: geometry.ground[0] },
    ...geometry.signal.slice(1).map((points, index) => ({
      pin: `pin${index + 3}`, alias: `signal_aux${index + 1}`, points,
    })),
    ...geometry.ground.slice(1).map((points, index) => ({
      pin: `pin${geometry.signal.length + index + 2}`, alias: `ground_aux${index + 1}`, points,
    })),
  ]
  return (
    <pushbutton
      {...props}
      name={name}
      doNotPlace
      pinLabels={Object.fromEntries(pads.map(({ pin, alias }) => [pin, [pin, alias]]))}
      footprint={
        <footprint>
          {pads.map(({ pin, alias, points }) =>
            createElement("smtpad", {
              key: pin,
              name: alias.toUpperCase(),
              portHints: [pin],
              shape: "polygon",
              points: points.map(([x, y]) => ({ x, y })),
            }),
          )}
        </footprint>
      }
    >
      {pads.slice(2).map(({ alias }) =>
        createElement("trace", {
          key: alias,
          name: `${name}_${alias}_join`,
          from: `.${name} > .${alias.startsWith("signal") ? "signal" : "ground"}`,
          to: `.${name} > .${alias}`,
        }),
      )}
    </pushbutton>
  )
}
